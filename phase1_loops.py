i = 10                              # i is a variable example used
while i >= 1:                       # telling it while i is greater than or equal to 1 then continue loop
    print(i)
    i -= 1                          # -= is basically saying i - whatever = answer
    if i == 0:                      # when i = 0 finish loop
        print("Done with loop")


